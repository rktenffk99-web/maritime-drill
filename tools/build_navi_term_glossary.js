'use strict';
// v5.55: key-term glossary for navigator (non-English) questions, built from the
// "용어 정리" section of each question's own explanation. Output: navi-term-glossary.js
//   node tools/build_navi_term_glossary.js          write
//   node tools/build_navi_term_glossary.js --check  fail if the file is stale
const fs=require('fs'),vm=require('vm'),zlib=require('zlib'),path=require('path');
const ROOT=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(ROOT,'index.html'),'utf8');
const s={};s.window=s;vm.createContext(s);
for(const m of html.matchAll(/id="md-bundle-past-explain-(\d+)_js">([^<]+)</g))vm.runInContext(zlib.gunzipSync(Buffer.from(m[2],'base64')).toString(),s);
for(const m of html.matchAll(/id="md-bundle-past-(20\d\d-navi\w*-\d)_js">([^<]+)</g)){
  try{vm.runInContext(zlib.gunzipSync(Buffer.from(m[2],'base64')).toString(),s)}catch(e){}
}
const QTEXT={},QINFO={};
for(const [id,p] of Object.entries(s.MD_PAST||{})){
  const [y,g,ses]=id.split('-');
  for(const q of p.questions||[]){
    const k=`${y}|${g}|${ses}|${q['과목']}|${q['번호']}`,ch=(q['선택지']||[]).map(String);
    QTEXT[k]=String(q['문제']||'')+' '+ch.join(' ');
    QINFO[k]={stem:String(q['문제']||''),choices:ch,answer:ch[q['정답']]||''};
  }
}
const dec=x=>String(x||'').replace(/<br\s*\/?>/g,'\n').replace(/<[^>]+>/g,'').replace(/&amp;/g,'&').replace(/&lt;/g,'<').replace(/&gt;/g,'>').replace(/&quot;/g,'"').replace(/&#39;/g,"'");
// First sentence only: a definition, not the reasoning that may point at the answer.
function firstSentence(def){
  let d=def.replace(/\s+/g,' ').trim();
  const m=d.match(/^(.{6,}?[.。!?])(?:\s|$)/);
  if(m)d=m[1];
  if(d.length>90)d=d.slice(0,88).replace(/[\s,·]+\S*$/,'')+'…';
  return d;
}
// A definition must not give the answer away (practice and mock exams alike).
const bigrams=x=>{const c=String(x).replace(/[^가-힣A-Za-z0-9]/g,'');const b=new Set();for(let i=0;i<c.length-1;i++)b.add(c.slice(i,i+2));return b;};
const cover=(a,b)=>{const A=bigrams(a),B=bigrams(b);if(!A.size)return 0;let n=0;for(const x of A)if(B.has(x))n++;return n/A.size;};
function givesAnswer(info,name,def){
  if(!info||!info.answer)return false;
  // "…을 무엇이라 하는가?" — the answer is a term; its definition restates the stem.
  if(info.answer.includes(name)&&cover(def,info.stem)>=0.3)return true;
  // "X에 대한 설명으로 옳은 것은?" — the definition reads like the correct choice.
  if(cover(info.answer,def)>=0.45&&bigrams(info.answer).size>=4)return true;
  return false;
}
let dropped=0;
// Everyday words or law names: a tooltip there is noise, not help.
const BASIC=new Set(['레이더','우현','좌현','선수','선미','변침','변속','등화','범선','동력선','유조선','해리','비중','선박소유자','선장','선원',
  '선박법','선원법','선박안전법','해양환경관리법','상법','해사안전법','해상교통안전법','선박입출항법','국제해상충돌방지규칙','해운법','항만법']);
const LEAK=/정답|오답|보기|㉮|㉯|㉰|㉱|㉴|㉵/;
const names=new Map(),perKey={};
for(const [k,e] of Object.entries(s.MD_EXPLAIN)){
  if(!/^\d{4}\|navi\w*\|\d\|[^|]+\|\d+$/.test(k)||/\|영어\|/.test(k))continue;
  const t=dec(e.html);const i=t.indexOf('용어 정리');if(i<0)continue;
  const j=t.indexOf('━━',t.indexOf('━━',i)+2);const sec=t.slice(i,j>0?j:undefined);
  const list=[];
  for(const line of sec.split('•').slice(1)){
    const m=line.match(/^\s*([^:：\n]{1,40}?)\s*[:：]\s*([^\n]+)/);if(!m)continue;
    const name=m[1].replace(/\s*[\(（][^)）]*[\)）]\s*/g,' ').replace(/\s+/g,' ').trim();
    if(name.length<2||name.length>20||/[•━]/.test(name))continue;
    const def=firstSentence(m[2]);
    if(def.length<4||LEAK.test(def))continue;
    // Only terms that are actually written in the question (stem or choices) get a tooltip.
    if(BASIC.has(name)||!QTEXT[k]||!QTEXT[k].includes(name))continue;
    if(givesAnswer(QINFO[k],name,def)){dropped++;continue;}
    if(!names.has(name))names.set(name,new Map());
    const defs=names.get(name);defs.set(def,(defs.get(def)||0)+1);
    if(!list.includes(name))list.push(name);
  }
  if(list.length)perKey[k]=list;
}
const ordered=[...names.keys()].sort();
const index=new Map(ordered.map((n,i)=>[n,i]));
const terms=ordered.map(n=>[n,[...names.get(n).entries()].sort((a,b)=>b[1]-a[1]||a[0].localeCompare(b[0]))[0][0]]);
const keys={};for(const k of Object.keys(perKey).sort())keys[k]=perKey[k].map(n=>index.get(n));
const out='// Generated by tools/build_navi_term_glossary.js — do not edit by hand.\n'+
  '// Key terms of each navigator question, taken from its explanation\'s 용어 정리 (first sentence only).\n'+
  'window.MDNaviTermGlossary='+JSON.stringify({terms,keys})+';\n';
const file=path.join(ROOT,'navi-term-glossary.js');
if(process.argv.includes('--check')){
  if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==out){console.error('navi-term-glossary.js is stale: run node tools/build_navi_term_glossary.js');process.exit(1);}
  console.log('navi term glossary up to date');
}else{fs.writeFileSync(file,out);console.log(`navi term glossary: ${dropped} answer-revealing dropped, ${terms.length} terms, ${Object.keys(keys).length} questions, ${out.length} bytes`);}
