"""Build figure-images-data.js from tools/figure_images/*.webp (re-runnable).

Each image is a crop of the official question booklet published by
한국해양수산연수원 (lems.seaman.or.kr, 문제 및 답안공개 > 기출문제), keyed as
"<exam id>|<subject>|<number>" — e.g. 2024-navi3-4|항해|8.
"""
from pathlib import Path
import base64, json, sys

root = Path(__file__).resolve().parents[1]
src = root / 'tools' / 'figure_images'
index = json.loads((src / 'index.json').read_text(encoding='utf-8'))
data = {}
for key, meta in sorted(index.items()):
    exam, subject, number = key.split('|')
    path = src / f'{exam}_{subject}_{number}.webp'
    if not path.exists():
        raise SystemExit(f'missing image for {key}: {path.name}')
    data[key] = {
        'src': 'data:image/webp;base64,' + base64.b64encode(path.read_bytes()).decode('ascii'),
        'w': meta['size'][0], 'h': meta['size'][1],
        'choices': meta['kind'] == 'blank',
    }
out = '// Generated by tools/build_figure_images.py. Do not edit by hand.\n'
out += '// 출처: 한국해양수산연수원 해기사 정기시험 기출문제집 (lems.seaman.or.kr)\n'
out += 'window.__MD_FIGURE_IMAGE_DATA=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n'
target = root / 'figure-images-data.js'
if '--check' in sys.argv:
    if target.read_text(encoding='utf-8') != out:
        raise SystemExit('figure-images-data.js is stale; run python tools/build_figure_images.py')
    print(f'figure images up to date: {len(data)}')
else:
    target.write_text(out, encoding='utf-8')
    print(f'figure images written: {len(data)}')
